/** Haufen aus Brocken (Kohle, Erze) in drei Tönen plus Glanzpunkten. */
function pile(base: RGB, dark: RGB, fleck: RGB, glint: RGB): WareArt {
  return {
    rows: [
      '.............',
      '.............',
      '.............',
      '.............',
      '.....KK......',
      '...KKfKKg....',
      '..KgKKKKfK...',
      '.KKfKKgKKKK..',
      '.KkKKKKfkKKK.',
      '..kkkkkkkkk..',
      '.............',
    ],
    pal: { K: base, k: dark, f: fleck, g: glint },
  };
}

/** Barren (Eisen, Gold). */
function ingot(light: RGB, mid: RGB, side: RGB, dark: RGB): WareArt {
  return {
    rows: [
      '.............',
      '.............',
      '.............',
      '.............',
      '...LLLLLLL...',
      '..LhLLLLLLM..',
      '.SSSSSSSSSMM.',
      '.SSSSSSSSSMM.',
      '.DDDDDDDDDD..',
      '.............',
      '.............',
    ],
    pal: { L: light, h: [255, 255, 255], S: mid, M: side, D: dark },
  };
}

